#!/usr/bin/env bash
# Q-021 / Q-034 static measurement framework MVP.
#
# Walks every task directory under evaluation/tasks/, collects per-form
# byte / line / approximate-token counts for each reference file, and
# emits a markdown report on stdout. Run from any directory; the script
# locates its own tasks/ via dirname $0.
#
# Token estimate uses bytes/4 — a commonly-cited rule-of-thumb for
# GPT-style BPE tokenizers. Real per-model counts vary; the framework
# README documents this caveat and the path to API-driven tokenization.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TASKS_DIR="$SCRIPT_DIR/tasks"

# Forms to report on, in column order. Each entry is "<filename-suffix>:<column-label>".
# Density forms (`reference.layer-a.density-v<n>`) are added in shipping
# order — each represents a measurement point after one shipping increment
# of the plan in `proposals/implemented/layer-a-density.md`. The file is
# only included in the report if it exists in the task directory.
FORMS=(
    "reference.python.py:Python+type-hints"
    "reference.canonical-json.json:Strand canonical dag-json"
    "reference.layer-a:Strand Layer A"
    "reference.layer-a.density-v1:Strand Layer A density v1"
    "reference.layer-a.density-v1.5:Strand Layer A density v1.5"
    "reference.layer-a.density-v2:Strand Layer A density v2"
    "reference.layer-a.density-v2.5:Strand Layer A density v2.5"
)

count_bytes() {
    if [[ -f "$1" ]]; then
        wc -c < "$1" | tr -d '[:space:]'
    else
        echo "-"
    fi
}

count_lines() {
    if [[ -f "$1" ]]; then
        wc -l < "$1" | tr -d '[:space:]'
    else
        echo "-"
    fi
}

approx_tokens() {
    local b
    b=$(count_bytes "$1")
    if [[ "$b" == "-" ]]; then
        echo "-"
    else
        echo $(( (b + 2) / 4 ))
    fi
}

cat <<'EOF'
# Q-021 static measurement report

Auto-generated by `evaluation/measure.sh`. Per-form byte / line /
approximate-token counts for each task's reference solution.

Caveats: token counts are estimates (`bytes/4` heuristic), not
per-tokenizer truth. See `README.md` § "What this MVP doesn't measure"
for the full set of dynamic metrics deferred to model-API integration.

EOF

for task_dir in "$TASKS_DIR"/*/; do
    task_name=$(basename "$task_dir")
    echo "## $task_name"
    echo
    if [[ -f "$task_dir/description.md" ]]; then
        first_line=$(grep -m1 '^# ' "$task_dir/description.md" | sed 's/^# //')
        if [[ -n "$first_line" ]]; then
            echo "_${first_line}_"
            echo
        fi
    fi
    echo "| Form | Bytes | Lines | Tokens (est) | × vs Python |"
    echo "|------|------:|------:|-------------:|------------:|"

    python_bytes=$(count_bytes "$task_dir/reference.python.py")

    for entry in "${FORMS[@]}"; do
        suffix="${entry%%:*}"
        label="${entry##*:}"
        file="$task_dir/$suffix"
        b=$(count_bytes "$file")
        l=$(count_lines "$file")
        t=$(approx_tokens "$file")
        if [[ "$b" != "-" && "$python_bytes" != "-" && "$python_bytes" != "0" ]]; then
            # Print ratio as e.g. 3.40
            ratio=$(awk -v a="$b" -v p="$python_bytes" 'BEGIN { printf "%.2f", a / p }')
        else
            ratio="-"
        fi
        echo "| $label | $b | $l | $t | $ratio |"
    done
    echo
done

# Summary roll-up
echo "## Aggregate"
echo
echo "| Form | Total bytes | Total tokens (est) | Geometric mean × vs Python |"
echo "|------|------------:|-------------------:|---------------------------:|"

# Compute totals per form
for entry in "${FORMS[@]}"; do
    suffix="${entry%%:*}"
    label="${entry##*:}"
    total_b=0
    total_t=0
    product_ratio=1
    count=0
    for task_dir in "$TASKS_DIR"/*/; do
        file="$task_dir/$suffix"
        py_file="$task_dir/reference.python.py"
        if [[ -f "$file" && -f "$py_file" ]]; then
            b=$(count_bytes "$file")
            t=$(approx_tokens "$file")
            py_b=$(count_bytes "$py_file")
            total_b=$((total_b + b))
            total_t=$((total_t + t))
            ratio=$(awk -v a="$b" -v p="$py_b" 'BEGIN { print a / p }')
            product_ratio=$(awk -v p="$product_ratio" -v r="$ratio" 'BEGIN { print p * r }')
            count=$((count + 1))
        fi
    done
    if [[ "$count" -gt 0 ]]; then
        geomean=$(awk -v p="$product_ratio" -v c="$count" 'BEGIN { printf "%.2f", exp(log(p) / c) }')
    else
        geomean="-"
    fi
    echo "| $label | $total_b | $total_t | $geomean |"
done

echo
cat <<'EOF'
## Interpretation

The geometric mean ratio against the Python+type-hints baseline is the
headline number. Q-034's §6 estimates put canonical dag-json at 2-5×
Python for non-trivial programs, and Layer A in the 0.8-1.3× range
after the Layer C inference fills in derivable annotations. Real
measurements diverge from these projections by task family — the
state-machine task carries more boilerplate than the pure-recursion
task in every form.

The numbers reported here are STATIC per-emission cost. The DYNAMIC
cost — how many emissions an agent needs to converge on a verified
program — multiplies on top. Without model-API integration, we can't
measure dynamic cost; with it, the headline becomes
"tokens-per-successful-task = static-cost × emissions-per-success",
the right per-task economics number.
EOF
